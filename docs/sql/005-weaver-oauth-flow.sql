CREATE TABLE IF NOT EXISTS WEAVER_OAUTH_FLOW (
 id_hash CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 state_hash CHAR(64) CHARACTER SET ascii NOT NULL UNIQUE,
 proof_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 platform VARCHAR(10) CHARACTER SET ascii NOT NULL,
 status VARCHAR(16) CHARACTER SET ascii NOT NULL DEFAULT 'pending',
 link_user_id CHAR(36) CHARACTER SET ascii NULL,
 subject VARCHAR(128) CHARACTER SET ascii NULL,
 email VARCHAR(254) CHARACTER SET ascii NULL,
 display_name VARCHAR(100) CHARACTER SET utf8mb4 NULL,
 error_code INT NULL,
 expires_at DATETIME(6) NOT NULL,
 INDEX(expires_at),
 FOREIGN KEY(link_user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
