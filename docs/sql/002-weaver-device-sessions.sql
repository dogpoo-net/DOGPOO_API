CREATE TABLE IF NOT EXISTS WEAVER_DEVICE_SESSION (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 kind VARCHAR(10) CHARACTER SET ascii NOT NULL,
 current_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 previous_hash CHAR(64) CHARACTER SET ascii NULL,
 last_request_hash CHAR(64) CHARACTER SET ascii NULL,
 proof_hash CHAR(64) CHARACTER SET ascii NULL,
 created_at DATETIME(6) NOT NULL,
 last_used_at DATETIME(6) NOT NULL,
 idle_expires_at DATETIME(6) NOT NULL,
 absolute_expires_at DATETIME(6) NOT NULL,
 INDEX(user_id), INDEX(idle_expires_at),
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS WEAVER_ACCESS_TOKEN (
 token_hash CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 device_id CHAR(36) CHARACTER SET ascii NOT NULL,
 expires_at DATETIME(6) NOT NULL,
 INDEX(expires_at),
 FOREIGN KEY(device_id) REFERENCES WEAVER_DEVICE_SESSION(id) ON DELETE CASCADE
) ENGINE=InnoDB;
