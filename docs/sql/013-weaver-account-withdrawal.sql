CREATE TABLE IF NOT EXISTS WEAVER_WITHDRAWAL_CHALLENGE (
 user_id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 token_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 expires_at DATETIME(6) NOT NULL,
 sent_at DATETIME(6) NOT NULL,
 attempts INT NOT NULL DEFAULT 0,
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
-- Minimal durable file-erasure work queue; removed when erasure succeeds.
CREATE TABLE IF NOT EXISTS WEAVER_ACCOUNT_ERASURE (
 resource_id CHAR(36) CHARACTER SET ascii NOT NULL,
 resource_kind VARCHAR(16) CHARACTER SET ascii NOT NULL,
 queued_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(resource_id,resource_kind)
) ENGINE=InnoDB;
