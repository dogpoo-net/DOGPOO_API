CREATE TABLE IF NOT EXISTS WEAVER_ACCOUNT_WORKSPACE (
 user_id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 revision BIGINT NOT NULL DEFAULT 0,
 migrated BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS WEAVER_WORKSPACE_ITEM (
 user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 item_key CHAR(64) CHARACTER SET ascii NOT NULL,
 kind VARCHAR(64) NOT NULL,
 item_id VARCHAR(512) NOT NULL,
 payload LONGTEXT NULL,
 deleted BOOLEAN NOT NULL DEFAULT FALSE,
 revision BIGINT NOT NULL,
 PRIMARY KEY(user_id,item_key), KEY(user_id,revision),
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS WEAVER_WORKSPACE_MEDIA (
 user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 media_key CHAR(64) CHARACTER SET ascii NOT NULL,
 media_id VARCHAR(512) NOT NULL,
 storage_path VARCHAR(1024) NOT NULL,
 media_type VARCHAR(8) NOT NULL,
 byte_size BIGINT NOT NULL,
 content_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 PRIMARY KEY(user_id,media_key),
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS WEAVER_GUEST_IMPORT (
 guest_id CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 source_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
