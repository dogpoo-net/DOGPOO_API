CREATE TABLE IF NOT EXISTS WEAVER_MEMO_COMMENT_DATA (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 workspace_id CHAR(36) CHARACTER SET ascii NOT NULL,
 memo_id VARCHAR(512) NOT NULL,
 author_id CHAR(36) CHARACTER SET ascii NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii NOT NULL,
 content TEXT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY(author_id,request_id),
 KEY(workspace_id,memo_id(128),id),
 FOREIGN KEY(workspace_id) REFERENCES WEAVER_ACCOUNT_WORKSPACE(user_id) ON DELETE CASCADE,
 FOREIGN KEY(author_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
