-- Bound metadata-lock waits; deploy with API writers stopped.
SET SESSION lock_wait_timeout=15;
CREATE TABLE IF NOT EXISTS WEAVER_PLAN_POLICY (
 code VARCHAR(16) CHARACTER SET ascii PRIMARY KEY,
 owned_limit INT NULL, storage_limit BIGINT NULL, document_limit INT NULL, editor_limit INT NULL,
 CHECK(owned_limit IS NULL OR owned_limit>=1), CHECK(storage_limit IS NULL OR storage_limit>=1),
 CHECK(document_limit IS NULL OR document_limit>=1), CHECK(editor_limit IS NULL OR editor_limit>=1)
) ENGINE=InnoDB;
INSERT IGNORE INTO WEAVER_PLAN_POLICY(code,editor_limit) VALUES('free',2),('standard',NULL),('pro',NULL);
CREATE TABLE IF NOT EXISTS WEAVER_WORKSPACE_SUBSCRIPTION (
 workspace_id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 plan VARCHAR(16) CHARACTER SET ascii NOT NULL,
 period_end DATETIME(6) NOT NULL,
 cancel_at_end BOOLEAN NOT NULL DEFAULT FALSE,
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(workspace_id) REFERENCES WEAVER_ACCOUNT_WORKSPACE(user_id) ON DELETE CASCADE,
 FOREIGN KEY(plan) REFERENCES WEAVER_PLAN_POLICY(code)
) ENGINE=InnoDB;
ALTER TABLE WEAVER_USER_ACCOUNT ADD COLUMN IF NOT EXISTS platform_role VARCHAR(16) NOT NULL DEFAULT 'user';
ALTER TABLE WEAVER_ACCOUNT_WORKSPACE ADD COLUMN IF NOT EXISTS edit_priority INT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS WEAVER_ACCOUNT_PROVISION (
 user_id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
-- Existing users must not receive another default workspace, even after deletion/transfer.
INSERT IGNORE INTO WEAVER_ACCOUNT_PROVISION(user_id) SELECT id FROM WEAVER_USER_ACCOUNT;
CREATE TABLE IF NOT EXISTS WEAVER_POLICY_AUDIT (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 actor_id CHAR(36) CHARACTER SET ascii NULL,
 action VARCHAR(64) NOT NULL, target_id VARCHAR(64) NOT NULL,
 details LONGTEXT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(actor_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE SET NULL
) ENGINE=InnoDB;
