CREATE TABLE IF NOT EXISTS WEAVER_ITEM_METADATA (
 workspace_id CHAR(36) CHARACTER SET ascii NOT NULL,
 item_key CHAR(64) CHARACTER SET ascii NOT NULL,
 created_by CHAR(36) CHARACTER SET ascii NULL,
 updated_by CHAR(36) CHARACTER SET ascii NULL,
 updated_at DATETIME(6) NOT NULL,
 PRIMARY KEY(workspace_id,item_key),
 FOREIGN KEY(workspace_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE,
 FOREIGN KEY(created_by) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE SET NULL,
 FOREIGN KEY(updated_by) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE SET NULL
) ENGINE=InnoDB;
