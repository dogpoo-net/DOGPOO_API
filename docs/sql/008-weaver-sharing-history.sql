CREATE TABLE IF NOT EXISTS WEAVER_WORKSPACE_MEMBER (
 workspace_id CHAR(36) CHARACTER SET ascii NOT NULL,
 user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 role VARCHAR(8) CHARACTER SET ascii NOT NULL,
 joined_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(workspace_id,user_id),
 FOREIGN KEY(workspace_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE,
 CHECK(role IN ('editor','viewer'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS WEAVER_WORKSPACE_INVITE (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 workspace_id CHAR(36) CHARACTER SET ascii NOT NULL,
 email VARCHAR(254) NOT NULL,
 role VARCHAR(8) CHARACTER SET ascii NOT NULL,
 token_hash CHAR(64) CHARACTER SET ascii NOT NULL UNIQUE,
 status VARCHAR(12) CHARACTER SET ascii NOT NULL DEFAULT 'pending',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 expires_at DATETIME(6) NOT NULL,
 KEY(workspace_id,status), KEY(email,status),
 FOREIGN KEY(workspace_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE,
 CHECK(role IN ('editor','viewer'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS WEAVER_DOCUMENT_HISTORY (
 workspace_id CHAR(36) CHARACTER SET ascii NOT NULL,
 document_key CHAR(64) CHARACTER SET ascii NOT NULL,
 document_id VARCHAR(512) NOT NULL,
 version BIGINT NOT NULL,
 actor_id CHAR(36) CHARACTER SET ascii NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 action VARCHAR(16) CHARACTER SET ascii NOT NULL,
 before_text LONGTEXT CHARACTER SET utf8mb4 NOT NULL,
 after_text LONGTEXT CHARACTER SET utf8mb4 NOT NULL,
 changes LONGTEXT CHARACTER SET utf8mb4 NOT NULL,
 added_chars INT NOT NULL,
 removed_chars INT NOT NULL,
 PRIMARY KEY(workspace_id,document_key,version),
 FOREIGN KEY(workspace_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE,
 FOREIGN KEY(actor_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS WEAVER_DOCUMENT_LOCK (
 workspace_id CHAR(36) CHARACTER SET ascii NOT NULL,
 document_key CHAR(64) CHARACTER SET ascii NOT NULL,
 user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 client_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 expires_at DATETIME(6) NOT NULL,
 PRIMARY KEY(workspace_id,document_key),
 FOREIGN KEY(workspace_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
