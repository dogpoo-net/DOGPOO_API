CREATE TABLE IF NOT EXISTS WEAVER_SOCIAL_ACCOUNT (
 provider VARCHAR(16) CHARACTER SET ascii NOT NULL,
 subject VARCHAR(128) CHARACTER SET ascii NOT NULL,
 user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(provider,subject),
 UNIQUE KEY(provider,user_id),
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE
) ENGINE=InnoDB;
