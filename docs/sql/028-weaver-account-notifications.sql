SET SESSION lock_wait_timeout=15;
CREATE TABLE IF NOT EXISTS WEAVER_ACCOUNT_NOTIFICATION (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 event_key VARCHAR(160) CHARACTER SET ascii NOT NULL,
 kind VARCHAR(20) CHARACTER SET ascii NOT NULL,
 workspace_id CHAR(36) CHARACTER SET ascii NULL,
 target_id VARCHAR(512) NOT NULL DEFAULT '',
 title VARCHAR(160) NOT NULL,
 body VARCHAR(1000) NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 read_at DATETIME(6) NULL,
 UNIQUE KEY notification_event(user_id,event_key),
 KEY notification_inbox(user_id,id),
 KEY notification_unread(user_id,read_at),
 FOREIGN KEY(user_id) REFERENCES WEAVER_USER_ACCOUNT(id) ON DELETE CASCADE,
 FOREIGN KEY(workspace_id) REFERENCES WEAVER_ACCOUNT_WORKSPACE(user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
